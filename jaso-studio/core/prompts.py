def build_uniquify_prompt(question: str, prev_answer: str, limit: int, count_mode: str,
                          flags: list) -> str:
    lo = int(limit * 0.92)
    mode_txt = "공백 포함" if count_mode == "incl" else "공백 제외"
    flag_lines = "\n".join(
        f"- \"{f.get('phrase','')}\" ({f.get('why','')}) → {f.get('fix','')}"
        for f in (flags or [])[:5]) or "- (지적 항목 없음 — 전반적인 관용구만 교체)"
    return f"""아래 답변이 다른 지원자들의 자소서와 문장 틀이 겹쳐 유사도 검사에 걸릴 위험이 있다.
이 지원자만 쓸 법한 표현으로 고쳐 써서 유사도를 낮춰라.

[문항] {question}
[기존 답변]
{prev_answer}

[겹치기 쉬운 문형 — 반드시 교체할 것]
{flag_lines}

고쳐 쓰기 규칙:
1) 사실·숫자·경험 내용은 단 하나도 바꾸지 않는다. 새 사실을 추가하지 않는다.
2) 소제목 1개, 두괄식, 상황→문제제기→원인→해결책→결과→입사 후 활용 구조는 유지한다.
3) 지적된 문형과 널리 쓰이는 자소서 관용구("기업 선택 시 가장 중요하게 생각하는 요인은",
   "행보에 동참해", "제가 지닌 전문성을 발휘", "다방면으로 노력한 결과",
   "긍정적인 영향을 미칠 것입니다" 등)는 뜻은 같되 문장 틀이 다른 새 문장으로 바꾼다.
4) 소제목도 흔한 패턴이면 이 지원자의 숫자·경험에서만 나올 수 있는 소제목으로 바꾼다.
5) 이 지원자의 구체 경험·숫자·현장 디테일을 문장의 뼈대로 삼아라. 그것이 유일함을 만든다.
6) 분량은 {mode_txt} {lo}~{limit}자 유지. 종결어미는 -습니다/-입니다 유지.
출력 형식(===ANSWER=== / ===NOTES===)을 지켜라. NOTES에는 무엇을 바꿨는지 1~2줄."""


def build_humanize_prompt(question: str, prev_answer: str, limit: int, count_mode: str,
                          flags: list) -> str:
    lo = int(limit * 0.92)
    mode_txt = "공백 포함" if count_mode == "incl" else "공백 제외"
    flag_lines = "\n".join(
        f"- {f.get('pattern','')}: \"{f.get('example','')}\" → {f.get('fix','')}"
        for f in (flags or [])[:5]) or "- (감지된 패턴 없음 — 전반적인 리듬만 사람답게)"
    return f"""아래 답변이 AI 작성으로 감지될 위험이 있다. 사람이 쓴 글로 읽히도록 고쳐 써라.

[문항] {question}
[기존 답변]
{prev_answer}

[감지된 위험 패턴 — 반드시 해소할 것]
{flag_lines}

고쳐 쓰기 규칙:
1) 사실·숫자·경험 내용은 단 하나도 바꾸지 않는다. 새 사실을 추가하지 않는다.
2) 소제목 1개, 두괄식, 상황→문제제기→원인→해결책→결과→입사 후 활용 구조는 유지한다.
3) 문장 길이 분산을 극단적으로 키운다: 문단마다 60자 이상 긴 문장 1개와 10자 안팎 초단문 1개를
   반드시 공존시킨다. 결정적 대목은 명사로 끊는다.
4) 상투 연결어를 지우고 내용의 인과로 잇는다. 3항 병렬은 한 번만 허용한다.
5) 현장감 있는 구체 묘사나 짧은 대사를 한 곳에 넣는다. 단, 지어내지 말고 기존 내용을 장면화한다.
6) 사람 특유의 흔적을 한 곳에만 심는다: 기존 내용을 재해석하는 회고 한 줄
   ("돌이켜보면 ~", "그때는 몰랐지만 ~" 류. 새 사실 금지) 또는 스스로 고쳐 말하는 한 문장.
7) 너무 매끈한 인과 사슬을 한 번은 비튼다 — 시행착오나 막혔던 순간을 기존 내용 안에서 드러낸다.
8) 분량은 {mode_txt} {lo}~{limit}자 유지. 종결어미는 -습니다/-입니다 유지.
출력 형식(===ANSWER=== / ===NOTES===)을 지켜라. NOTES에는 무엇을 바꿨는지 1~2줄."""


def build_length_fix_prompt(current: int, lo: int, hi: int, count_mode: str) -> str:
    mode_txt = "공백 포함" if count_mode == "incl" else "공백 제외"
    if current > hi:
        return (f"위 답변은 {mode_txt} {current}자로 목표({lo}~{hi}자)를 초과했다. "
                f"{mode_txt} {lo}~{hi}자로 압축하라. 삭제 우선순위: 수식어 → 중복 설명 → 부가 에피소드. "
                f"소제목·두괄식·스토리 구조·결과 수치는 유지하라. 같은 출력 형식으로 다시 써라.")
    return (f"위 답변은 {mode_txt} {current}자로 목표({lo}~{hi}자)보다 짧다. "
            f"{mode_txt} {lo}~{hi}자로 늘려라. 확장 우선순위: 해결 행동의 구체 묘사 → 원인 분석 과정 → 입사 후 활용 방안. "
            f"새로운 사실을 지어내지 말고 주어진 재료 안에서 확장하라. 같은 출력 형식으로 다시 써라.")


